    #[test]
    fn matches_mpmath() {
        let mut worst = (0.0_f64, 0.0_f64);
        for (l, eta, rho, p, s) in REFERENCE {
            let (ours_p, ours_s) = penetrability_shift(l, eta, rho);
            let rel_p = (ours_p - p).abs() / p;
            let abs_s = (ours_s - s).abs() / s.abs().max(1.0);
            worst = (worst.0.max(rel_p), worst.1.max(abs_s));
            assert!(
                rel_p < 1e-9,
                "P: l={l} eta={eta} rho={rho}: {ours_p} vs {p}"
            );
            assert!(
                abs_s < 1e-9,
                "S: l={l} eta={eta} rho={rho}: {ours_s} vs {s}"
            );
        }
        eprintln!(
            "Coulomb against mpmath: P {:.2e}, S {:.2e}",
            worst.0, worst.1
        );
    }

    /// At η = 0 the Coulomb functions are the hard-sphere ones.
    #[test]
    fn eta_zero_is_hard_sphere() {
        for l in 0..4 {
            for rho in [0.2, 1.0, 3.0, 12.0] {
                let (p, s) = penetrability_shift(l, 0.0, rho);
                let hp = crate::penetrability::penetrability(l, rho);
                let hs = crate::penetrability::shift_factor(l, rho);
                assert!((p - hp).abs() <= 1e-10 * hp, "l={l} rho={rho}: {p} vs {hp}");
                assert!(
                    (s - hs).abs() <= 1e-10 * hs.abs().max(1.0),
                    "l={l} rho={rho}"
                );
            }
        }
    }
